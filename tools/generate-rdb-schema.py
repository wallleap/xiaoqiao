"""Package the reviewed SQL as complete statements; no persistent DB is opened."""
import argparse
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/database/schema-v1.sql'
TARGET = ROOT / 'entry/src/main/ets/data/rdb/ReviewSchema.ets'


def statements(source):
    result, pending = [], ''
    for line in source.splitlines(keepends=True):
        pending += line
        if sqlite3.complete_statement(pending):
            lines = pending.splitlines()
            while lines and (not lines[0].strip() or lines[0].lstrip().startswith('--')):
                lines.pop(0)
            text = '\n'.join(lines).strip()
            if text:
                result.append(text)
            pending = ''
    assert not pending.strip(), 'Incomplete final SQL statement'
    return result


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    raw = SOURCE.read_bytes()
    sql = statements(raw.decode())
    with sqlite3.connect(':memory:') as db:
        for statement in sql:
            db.execute(statement)
        assert db.execute('PRAGMA foreign_keys').fetchone()[0] == 1
        assert not db.execute('PRAGMA foreign_key_check').fetchall()
    output = '// Generated by tools/generate-rdb-schema.py; edit docs/database/schema-v1.sql instead.\n'
    output += '// P0 validation only: not wired into application startup or a production migration.\n'
    output += f'export const REVIEW_SCHEMA_SHA256: string = "{hashlib.sha256(raw).hexdigest()}";\n'
    output += 'export const REVIEW_SCHEMA_STATEMENTS: string[] = [\n'
    output += ',\n'.join('  '+json.dumps(s, ensure_ascii=False) for s in sql)
    output += '\n];\n'
    if args.check:
        assert TARGET.read_text() == output, 'ReviewSchema.ets is stale; regenerate it'
        print(f'Schema package matches source: {len(sql)} complete statements')
    else:
        TARGET.parent.mkdir(parents=True, exist_ok=True)
        TARGET.write_text(output)
        print(f'Generated {TARGET.relative_to(ROOT)}: {len(sql)} complete statements')


if __name__ == '__main__':
    main()
