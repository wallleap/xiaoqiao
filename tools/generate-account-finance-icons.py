#!/usr/bin/env python3
"""Generate finance tool variants from audited local SVGs; no network access."""
from pathlib import Path
import copy
import hashlib
import json
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/finance-tool-icons'
MEDIA = ROOT / 'entry/src/main/resources/base/media'
NS = 'http://www.w3.org/2000/svg'
ET.register_namespace('', NS)


def read_svg(filename, digest):
    raw = (SOURCE / 'source' / filename).read_bytes()
    if hashlib.sha256(raw).hexdigest() != digest:
        raise ValueError('Source hash mismatch: ' + filename)
    root = ET.fromstring(raw)
    allowed = {'svg', 'path', 'g', 'defs', 'linearGradient', 'radialGradient',
               'stop', 'clipPath', 'rect', 'circle', 'mask'}
    for node in root.iter():
        if node.tag.split('}')[-1] not in allowed:
            raise ValueError('Unexpected SVG node: ' + node.tag)
        if any(k.startswith('on') or k.endswith('href') for k in node.attrib):
            raise ValueError('External or executable SVG attribute')
    return root


def white_variant(root, key):
    # UnionPay has opaque white lettering on colored panels. Cut letters out
    # rather than painting both panels and letters white and losing the logo.
    if key == 'unionpay':
        original = list(root)
        root.clear()
        defs = ET.SubElement(root, '{' + NS + '}defs')
        mask = ET.SubElement(defs, '{' + NS + '}mask', {
            'id': 'unionpay_white_cutout', 'maskUnits': 'userSpaceOnUse',
            'x': '-20', 'y': '-80', 'width': '360', 'height': '360'})
        for node in original:
            node.set('fill', '#000000' if node.get('fill', '').lower() == '#fff' else '#FFFFFF')
            mask.append(node)
        ET.SubElement(root, '{' + NS + '}rect', {'x': '-20', 'y': '-80',
            'width': '360', 'height': '360', 'fill': '#FFFFFF',
            'mask': 'url(#unionpay_white_cutout)'})
        return
    for node in root.iter():
        if node.tag.split('}')[-1] == 'path' and node.get('fill', '') != 'none':
            node.set('fill', '#FFFFFF')


def main():
    catalog = json.loads((SOURCE / 'catalog.json').read_text())
    styles = ['// Generated by tools/generate-account-finance-icons.py; do not edit by hand.',
              'export interface FinanceAccountStyle {', '  key: string;', '  name: string;',
              '  brand: string;', '  color: string;', '  variant?: string;',
              '  searchText?: string;', '}', '',
              'export const FINANCE_ACCOUNT_STYLES: FinanceAccountStyle[] = [']
    icons = ['// Generated by tools/generate-account-finance-icons.py; do not edit by hand.',
             'export function financeAccountIcon(key: string): Resource | undefined {', '  switch (key) {']
    report = ['# 国内金融工具图标清单', '',
              '<!-- Generated by tools/generate-account-finance-icons.py; do not edit by hand. -->', '',
              '整理日期：2026-11-19。7 个标识，彩色／白色两版，共 14 个可选样式。', '',
              '只扩展账户的图标素材，不新增账户类型、信用额度、授信或金融服务接口。芝麻信用仅作为可选标识。', '',
              '支付宝、微信、花呗、借呗保留原白色标识及图标键；彩色与新增标识采用图标集素材。',
              'SVG 原件及 SHA-256 保存在 tools/finance-tool-icons/catalog.json。彩色版本统一图形边界，白色银联以镂空保留字形。', '',
              '| 名称 | 白色键 | 彩色键 | 彩色素材来源 |', '|---|---|---|---|']
    seen = set()
    for row in catalog['tools']:
        original = read_svg(row['sourceFile'], row['sha256'])
        for variant in ('monochrome', 'color'):
            key = row['key'] + ('_color' if variant == 'color' else '')
            if key in seen:
                raise ValueError('Duplicate key: ' + key)
            seen.add(key)
            svg = copy.deepcopy(original)
            if variant == 'monochrome' and 'monochromeFile' in row:
                svg = read_svg(row['monochromeFile'], row['monochromeSha256'])
            else:
                if variant == 'monochrome':
                    white_variant(svg, row['key'])
                svg.set('viewBox', ' '.join(f'{v:.5f}' for v in row['viewBox']))
            svg.set('width', '128')
            svg.set('height', '128')
            resource = 'accounts_finance_' + key
            (MEDIA / (resource + '.svg')).write_text(ET.tostring(svg, encoding='unicode') + '\n')
            style = {'key': key, 'name': row['name'], 'brand': row['brand'],
                     'color': row['color'], 'variant': variant,
                     'searchText': ' '.join([row['sourceName']] + row['keywords'])}
            styles.append('  ' + json.dumps(style, ensure_ascii=False) + ',')
            icons.append(f"    case '{key}': return $r('app.media.{resource}');")
        report.append(f"| {row['name']} | `{row['key']}` | `{row['key']}_color` | [查看]({row['pageUrl']}) |")
    styles.extend(['];', ''])
    icons.extend(['    default: return undefined;', '  }', '}', ''])
    (ROOT / 'entry/src/main/ets/domain/model/FinanceAccountStyles.ets').write_text('\n'.join(styles))
    (ROOT / 'entry/src/main/ets/presentation/ledger/FinanceAccountIcons.ets').write_text('\n'.join(icons))
    report.extend(['', '## 待补素材', '', '、'.join(catalog['missing']) + '。', '',
                   '目录未检索到准确的独立标识，暂不接入。模糊匹配不作来源：网商银行不代替网商贷；微信支付不代替支付分；芝麻信用不代替信用购；京东科技不代替白条／金条；度小满轩辕不代替度小满金融。', '',
                   '素材目录并非官方授权库；保留来源记录不等于取得商标授权，发布前仍需核对品牌的使用规范。', ''])
    (ROOT / 'docs/development/finance-tool-icon-inventory.md').write_text('\n'.join(report))
    print(f'Generated {len(catalog["tools"])} finance tools, {len(seen)} styles')


if __name__ == '__main__':
    main()
