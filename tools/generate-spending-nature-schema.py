"""Generate the reviewed v3 spending-nature migration without opening a persistent DB."""
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BASE = ROOT / 'docs/database/schema-v1.sql'
TRANSFER = ROOT / 'docs/database/schema-v2-transfer.sql'
SOURCE = ROOT / 'docs/database/schema-v3-spending-nature.sql'
TARGET = ROOT / 'entry/src/main/ets/data/rdb/SpendingNatureSchema.ets'


def statements(path):
    result, pending = [], ''
    for line in path.read_text().splitlines(keepends=True):
        pending += line
        if sqlite3.complete_statement(pending):
            lines = pending.splitlines()
            while lines and (not lines[0].strip() or lines[0].lstrip().startswith('--')):
                lines.pop(0)
            text = '\n'.join(lines).strip()
            if text:
                result.append(text)
            pending = ''
    assert not pending.strip(), 'Incomplete final SQL statement'
    return result


def main():
    raw = SOURCE.read_bytes()
    sql = statements(SOURCE)
    with sqlite3.connect(':memory:') as db:
        db.execute('PRAGMA foreign_keys=ON')
        for statement in statements(BASE) + statements(TRANSFER):
            db.execute(statement)
        for statement in sql:
            db.execute(statement)
        assert not db.execute('PRAGMA foreign_key_check').fetchall()
        assert db.execute('PRAGMA quick_check').fetchone()[0] == 'ok'
        assert db.execute('SELECT COUNT(*) FROM spending_natures WHERE built_in=1').fetchone()[0] == 4
    output = '// Generated by tools/generate-spending-nature-schema.py.\n'
    output += f'export const SPENDING_NATURE_SCHEMA_SHA256: string = "{hashlib.sha256(raw).hexdigest()}";\n'
    output += 'export const SPENDING_NATURE_SCHEMA_STATEMENTS: string[] = [\n'
    output += ',\n'.join('  ' + json.dumps(item, ensure_ascii=False) for item in sql)
    output += '\n];\n'
    TARGET.write_text(output)
    print(f'Generated {TARGET.relative_to(ROOT)}: {len(sql)} complete statements')


if __name__ == '__main__':
    main()
