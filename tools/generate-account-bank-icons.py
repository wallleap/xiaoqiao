#!/usr/bin/env python3
"""Generate audited bank icon resources and ArkTS catalogs from local source SVGs."""
from pathlib import Path
import colorsys
import hashlib
import json
import re
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'tools/bank-icons'
MEDIA = ROOT / 'entry/src/main/resources/base/media'
ET.register_namespace('', 'http://www.w3.org/2000/svg')


def accent(root):
    scores, hues = {}, {}
    for node in root.iter():
        paint = node.get('fill', node.get('stop-color', ''))
        if not re.fullmatch(r'#[\da-fA-F]{6}', paint):
            continue
        rgb = [int(paint[i:i + 2], 16) / 255 for i in (1, 3, 5)]
        hue, saturation, value = colorsys.rgb_to_hsv(*rgb)
        if saturation < .2 or value < .25:
            continue
        color = paint.upper()
        weight = max(1, len(re.findall(r'[-+]?(?:\d*\.)?\d+', node.get('d', ''))))
        scores[color] = scores.get(color, 0) + weight * saturation
        hues[color] = hue
    if not scores:
        return '#5378B8'
    def family(color):
        return sum(weight for other, weight in scores.items()
                   if min(abs(hues[color] - hues[other]), 1 - abs(hues[color] - hues[other])) <= 30 / 360)
    return max(scores, key=lambda c: (family(c), scores[c]))


def monochrome(node, definitions=False):
    tag = node.tag.split('}')[-1]
    definitions = definitions or tag in ('defs', 'mask')
    if not definitions and tag != 'svg':
        # Keep transparency, geometric holes and mask contents; flatten visible paints only.
        if node.get('fill', 'black') != 'none':
            node.set('fill', '#FFFFFF')
        if node.get('stroke', 'none') != 'none':
            node.set('stroke', '#FFFFFF')
    for child in node:
        monochrome(child, definitions)


def main():
    rows = json.loads((SOURCE / 'catalog.json').read_text())['banks']
    styles = ['// Generated by tools/generate-account-bank-icons.py; do not edit by hand.',
              'export interface BankAccountStyle {', '  key: string;', '  name: string;',
              '  brand: string;', '  color: string;', '  variant?: string;', '  historical?: boolean;', '  searchText?: string;', '}',
              '', 'export const BANK_ACCOUNT_STYLES: BankAccountStyle[] = [']
    resources = ['// Generated by tools/generate-account-bank-icons.py; do not edit by hand.',
                 'export function bankAccountIcon(key: string): Resource | undefined {', '  switch (key) {']
    seen = set()
    resource_names = set()
    for row in rows:
        raw = (SOURCE / 'source' / row['sourceFile']).read_bytes()
        if hashlib.sha256(raw).hexdigest() != row['sha256']:
            raise ValueError('Source hash mismatch: ' + row['sourceFile'])
        root = ET.fromstring(raw)
        for node in root.iter():
            if node.tag.split('}')[-1] not in {'svg', 'path', 'g', 'defs', 'linearGradient', 'radialGradient', 'stop', 'mask'}:
                raise ValueError('Unexpected SVG node: ' + node.tag)
            if any(k.startswith('on') or k.endswith('href') for k in node.attrib):
                raise ValueError('External or executable SVG attribute')
        color = accent(root)
        root.set('viewBox', ' '.join(f'{v:.5f}' for v in row['viewBox']))
        root.set('width', '128'); root.set('height', '128')
        for variant in ('color', 'monochrome'):
            key = row['key'] + ('_color' if variant == 'color' else '')
            if key in seen:
                raise ValueError('Duplicate icon key: ' + key)
            seen.add(key)
            svg = ET.fromstring(ET.tostring(root))
            if variant == 'monochrome':
                monochrome(svg)
            resource = 'accounts_' + row.get('resourceKey', row['key']) + ('_color' if variant == 'color' else '')
            if not re.fullmatch(r'[a-z][a-z0-9_]*', resource) or resource in resource_names:
                raise ValueError('Invalid or duplicate resource name: ' + resource)
            resource_names.add(resource)
            output = ET.tostring(svg, encoding='unicode') + '\n'
            (MEDIA / (resource + '.svg')).write_text(output)
            # Remove only this catalog item's previous generated filename, and
            # only when identical; never sweep unrelated or modified resources.
            previous = MEDIA / ('accounts_' + key + '.svg')
            if previous.name != resource + '.svg' and previous.exists():
                if previous.read_text() != output:
                    raise ValueError('Modified legacy resource requires review: ' + str(previous))
                previous.unlink()
            styles.append('  { key: ' + json.dumps(key) + ', name: ' + json.dumps(row['name'], ensure_ascii=False) +
                          ', brand: ' + json.dumps(row['brand']) + ', color: ' + json.dumps(color) +
                          ', variant: ' + json.dumps(variant) + ', historical: ' + str(row['historical']).lower() +
                          ', searchText: ' + json.dumps(' '.join([row['sourceName']] + row['keywords']), ensure_ascii=False) + ' },')
            resources.append(f"    case '{key}': return $r('app.media.{resource}');")
    styles.extend(['];', ''])
    resources.extend(['    default: return undefined;', '  }', '}', ''])
    (ROOT / 'entry/src/main/ets/domain/model/BankAccountStyles.ets').write_text('\n'.join(styles))
    (ROOT / 'entry/src/main/ets/presentation/ledger/BankAccountIcons.ets').write_text('\n'.join(resources))
    report = ['# 银行图标清单', '',
              '<!-- Generated by tools/generate-account-bank-icons.py; do not edit by hand. -->', '',
              f'来源：[图标集金融银行目录](https://www.tubiao.cn/directory/finance-banking?sort=alphabetical)。共 {len(rows)} 条名称记录，每条彩色/白色两版。', '',
              '本清单是素材目录，不是现存银行机构名录；未标历史不等于已逐一核验经营状态。历史项默认不在选择器显示，可手动包含。', '',
              '每个来源 SVG 的 SHA-256、下载地址、网页地址、名称及几何边界记录于 tools/bank-icons/catalog.json。', '',
              '文件名采用来源目录中的英文简称（小写）；简称用于本项目素材识别，不作为统一银行机构代码。账户内部兼容键保持不变，无需数据库迁移。', '',
              '| 银行/来源名称 | 简称 | 资源文件（白色／彩色） | 兼容图标键（白色） | 来源页面 | 历史标识 |',
              '|---|---|---|---|---|---|']
    for row in rows:
        resource = 'accounts_' + row.get('resourceKey', row['key'])
        report.append(f"| {row['sourceName']} | {row.get('abbreviation', '')} | `{resource}.svg` / `{resource}_color.svg` | `{row['key']}` | [查看]({row['pageUrl']}) | {'是' if row['historical'] else '—'} |")
    report.append('')
    (ROOT / 'docs/development/bank-icon-inventory.md').write_text('\n'.join(report))
    print(f'Generated {len(rows)} bank records, {len(seen)} color/monochrome styles')


if __name__ == '__main__':
    main()
