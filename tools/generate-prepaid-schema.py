"""Package the v8 SQL migration; does not open a database or execute SQL."""
import hashlib
import json
import sqlite3
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'docs/database/schema-v8-prepaid.sql'
TARGET = ROOT / 'entry/src/main/ets/data/rdb/PrepaidSchema.ets'

def main():
    raw = SOURCE.read_bytes()
    result, pending = [], ''
    for line in raw.decode().splitlines(keepends=True):
        pending += line
        if sqlite3.complete_statement(pending):
            lines = pending.splitlines()
            while lines and (not lines[0].strip() or lines[0].lstrip().startswith('--')):
                lines.pop(0)
            if lines:
                result.append('\n'.join(lines).strip())
            pending = ''
    if pending.strip():
        raise ValueError('Incomplete SQL statement')
    TARGET.write_text('// Generated by tools/generate-prepaid-schema.py; edit the v8 SQL source.\n'
        + f'export const PREPAID_SCHEMA_SHA256: string = "{hashlib.sha256(raw).hexdigest()}";\n'
        + 'export const PREPAID_SCHEMA_STATEMENTS: string[] = [\n'
        + ',\n'.join('  ' + json.dumps(s, ensure_ascii=False) for s in result) + '\n];\n')
    print(f'Generated {len(result)} SQL statements (not executed).')

if __name__ == '__main__':
    main()
