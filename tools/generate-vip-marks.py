"""Generate the silver counterpart of the supplied faceted VIP emblem."""
from copy import deepcopy
from pathlib import Path
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / 'entry/src/main/resources/base/media'
NS = 'http://www.w3.org/2000/svg'
ET.register_namespace('', NS)
# The newer supplied emblem retains its multi-tone faceting; only its silver counterpart is derived.
source = ET.parse(MEDIA / 'vip_emblem.svg').getroot()
root = deepcopy(source)
for node in root.iter():
    for attribute in ['fill', 'stroke']:
        color = node.attrib.get(attribute, '')
        if len(color) == 7 and color.startswith('#'):
            red, green, blue = [int(color[index:index + 2], 16) for index in [1, 3, 5]]
            gray = round(red * 0.2126 + green * 0.7152 + blue * 0.0722)
            node.set(attribute, '#' + format(gray, '02X') * 3)
target = MEDIA / 'vip_emblem_silver.svg'
target.write_text('<!-- Generated by tools/generate-vip-marks.py from vip_emblem.svg; do not hand edit. -->\n'
                  + ET.tostring(root, encoding='unicode') + '\n')
print('Generated ' + target.name + '; original gold emblem unchanged')
