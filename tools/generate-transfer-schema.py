"""Package the additive transfer extension; validates only an in-memory SQLite database."""
import argparse
import hashlib
import importlib.util
import json
import sqlite3
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location('base_schema', ROOT / 'tools/generate-rdb-schema.py')
base = importlib.util.module_from_spec(spec)
spec.loader.exec_module(base)
source = ROOT / 'docs/database/schema-v2-transfer.sql'
target = ROOT / 'entry/src/main/ets/data/rdb/TransferSchema.ets'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
raw = source.read_bytes()
statements = base.statements(raw.decode())
with sqlite3.connect(':memory:') as db:
    for sql in base.statements(base.SOURCE.read_text()): db.execute(sql)
    for sql in statements: db.execute(sql)
    assert not db.execute('PRAGMA foreign_key_check').fetchall()
output = '// Generated by tools/generate-transfer-schema.py; edit docs/database/schema-v2-transfer.sql.\n'
output += f'export const TRANSFER_SCHEMA_SHA256: string = "{hashlib.sha256(raw).hexdigest()}";\n'
output += 'export const TRANSFER_SCHEMA_STATEMENTS: string[] = [\n'
output += ',\n'.join('  '+json.dumps(sql, ensure_ascii=False) for sql in statements) + '\n];\n'
if args.check:
    assert target.read_text() == output, 'TransferSchema.ets is stale'
    print(f'Transfer extension matches source: {len(statements)} statements')
else:
    target.write_text(output)
    print(f'Generated transfer extension: {len(statements)} statements')
