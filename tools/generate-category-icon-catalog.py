#!/usr/bin/env python3
"""Generate static ArkUI references and verified legacy aliases for bundled category icons."""
from pathlib import Path
import argparse
import json
import re
import subprocess
import xml.etree.ElementTree as ET

ROOT = Path(__file__).resolve().parents[1]
MEDIA = ROOT / 'entry/src/main/resources/base/media'
OUTPUT = ROOT / 'entry/src/main/ets/presentation/ledger/ColorfulCategoryIcons.ets'
ALIASES = ROOT / 'tools/category-icon-aliases.json'


def fingerprint(data: bytes) -> tuple:
    root = ET.fromstring(data)
    # Export metadata changed during replacement; compare ordered SVG geometry and paint attributes.
    ignored = {'p-id', 'class', 'style', 'version'}
    return (root.attrib.get('viewBox'), tuple(
        (node.tag, tuple(sorted((key, value) for key, value in node.attrib.items() if key not in ignored)))
        for node in root.iter() if node is not root))


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--legacy-ref', help='Build aliases by matching old colorful_icon SVGs at a Git ref')
    args = parser.parse_args()
    paths = sorted(path for path in MEDIA.glob('colorful_icon*.svg') if re.fullmatch(r'colorful_icon\d+', path.stem))
    # Keep database keys stable; only bundled resource filenames carry the colorful_ namespace.
    names = [path.stem.removeprefix('colorful_') for path in paths]
    if not names:
        raise ValueError('No category icon resources found')
    if args.legacy_ref:
        current = {}
        for path in paths:
            current.setdefault(fingerprint(path.read_bytes()), path.stem.removeprefix('colorful_'))
        prefix = MEDIA.relative_to(ROOT).as_posix() + '/'
        historical = subprocess.check_output(
            ['git', 'ls-tree', '-r', '--name-only', args.legacy_ref, prefix], cwd=ROOT, text=True).splitlines()
        aliases = {}
        for path in historical:
            if not re.fullmatch(r'colorful_icon_\d+\.svg', Path(path).name):
                continue
            data = subprocess.check_output(['git', 'show', f'{args.legacy_ref}:{path}'], cwd=ROOT)
            target = current.get(fingerprint(data))
            if target is None:
                raise ValueError(f'No geometry/paint match for {path}; map explicitly before regenerating')
            aliases[Path(path).stem] = target
        if not aliases:
            raise ValueError('No legacy icons found at the requested Git ref')
        ALIASES.write_text(json.dumps(dict(sorted(aliases.items())), indent=2) + '\n')
    aliases = json.loads(ALIASES.read_text())
    if not set(aliases.values()).issubset(names):
        raise ValueError('Legacy alias refers to a missing icon resource')
    lines = ['// Generated by tools/generate-category-icon-catalog.py; do not edit by hand.',
             'export interface ColorfulCategoryIcon {', '  key: string;', '  resource: Resource;', '}', '',
             'export const COLORFUL_CATEGORY_ICONS: ColorfulCategoryIcon[] = [']
    lines += [f"  {{ key: '{name}', resource: $r('app.media.{path.stem}') }}," for name, path in zip(names, paths)]
    lines += ['];', '', 'export const LEGACY_COLORFUL_ICON_KEYS: Record<string, string> = {']
    lines += [f"  '{key}': '{value}'," for key, value in sorted(aliases.items())]
    lines += ['};', '']
    OUTPUT.write_text('\n'.join(lines))
    print(f'Generated {len(names)} category icon references and {len(aliases)} legacy aliases')


if __name__ == '__main__':
    main()
